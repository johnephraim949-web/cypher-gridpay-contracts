import StyleDictionary from 'style-dictionary';

const variable = (name) => `--gp-${name}`;
const tokenName = ({ path }) => path.slice(1).join('-');

const measurement = ({ value, unit }) => `${value}${unit}`;
const rgb = ({ components, alpha = 1 }) =>
  `rgb(${components.map((channel) => Math.round(channel * 255)).join(' ')} / ${alpha})`;

const serialize = {
  color: (value) => value.hex ?? rgb(value),
  dimension: measurement,
  duration: measurement,
  fontFamily: (value) => value.map((family) => /\s/.test(family) ? `"${family}"` : family).join(', '),
  fontWeight: String,
  number: String,
  cubicBezier: (value) => `cubic-bezier(${value.join(', ')})`,
  shadow: ({ offsetX, offsetY, blur, spread, color }) =>
    `${[offsetX, offsetY, blur, spread].map(measurement).join(' ')} ${rgb(color)}`,
};

function collect(dictionary) {
  const groups = { base: {}, light: {}, dark: {} };
  for (const token of dictionary.allTokens) {
    groups[token.path[0]][tokenName(token)] = serialize[token.$type](token.$value);
  }
  return groups;
}

function block(selector, tokens) {
  const declarations = Object.entries(tokens)
    .map(([name, value]) => `  ${variable(name)}: ${value};`)
    .join('\n');
  return `${selector} {\n${declarations}\n}`;
}

StyleDictionary.registerFormat({
  name: 'gridpay/css',
  format: ({ dictionary }) => {
    const { base, light, dark } = collect(dictionary);
    const reduced = Object.fromEntries(Object.keys(base)
      .filter((name) => name.startsWith('motion-duration-'))
      .map((name) => [name, '0ms']));
    return [
      '/* Generated by packages/design-tokens. */',
      block(':root, [data-theme="light"]', { ...base, ...light, 'color-mode': 'light' }),
      block('[data-theme="dark"]', { ...dark, 'color-mode': 'dark' }),
      `@media (prefers-reduced-motion: reduce) {\n${block(':root, [data-theme]', reduced)}\n}`,
      [
        '.gp-numeric {',
        '  font-family: var(--gp-font-mono);',
        '  font-variant-numeric: tabular-nums slashed-zero;',
        '  font-variant-ligatures: none;',
        '}',
        '[data-theme], :root { color-scheme: var(--gp-color-mode); }',
      ].join('\n'),
    ].join('\n\n') + '\n';
  },
});

StyleDictionary.registerFormat({
  name: 'gridpay/typescript',
  format: ({ dictionary }) => {
    const { base, light, dark } = collect(dictionary);
    const keys = JSON.stringify(Object.keys({ ...base, ...light }));
    return [
      '/* Generated by Style Dictionary. */',
      `export const tokenNames = ${keys} as const;`,
      'export type TokenName = typeof tokenNames[number];',
      'export type ThemeName = "light" | "dark";',
      'export type Theme = Readonly<Record<TokenName, string>>;',
      `const base = ${JSON.stringify(base, null, 2)};`,
      'export const themes: Readonly<Record<ThemeName, Theme>> = {',
      `  light: { ...base, ...${JSON.stringify(light, null, 2)} },`,
      `  dark: { ...base, ...${JSON.stringify(dark, null, 2)} },`,
      '};\n',
    ].join('\n');
  },
});

const dictionary = new StyleDictionary({
  usesDtcg: true,
  source: ['tokens.json'],
  platforms: {
    web: {
      transforms: ['name/kebab'],
      files: [
        { destination: '../../apps/web/src/styles/tokens.css', format: 'gridpay/css' },
        { destination: 'dist/themes.ts', format: 'gridpay/typescript' },
      ],
    },
  },
});
await dictionary.buildAllPlatforms();
