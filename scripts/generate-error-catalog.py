#!/usr/bin/env python3
"""Generate and verify the cross-contract error catalog.

Parses every ``#[contracterror]`` enum under ``core/`` and ``orchestrator/``,
cross-checks the numeric discriminants against ``sdk/typescript/src/errors.ts``,
and regenerates ``docs/ERROR_CODES.md``.

Usage:
    python3 scripts/generate-error-catalog.py            # regenerate docs
    python3 scripts/generate-error-catalog.py --check    # CI drift check
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS_PATH = ROOT / "docs" / "ERROR_CODES.md"
TS_PATH = ROOT / "sdk" / "typescript" / "src" / "errors.ts"

# Contract display name -> Rust source file that declares its #[contracterror] enum.
CONTRACTS = [
    ("Payment", ROOT / "core" / "contracts" / "payment" / "src" / "errors.rs"),
    ("Escrow", ROOT / "core" / "contracts" / "escrow" / "src" / "lib.rs"),
    ("Refund", ROOT / "core" / "contracts" / "refund" / "src" / "lib.rs"),
    ("Admin", ROOT / "orchestrator" / "contracts" / "admin" / "src" / "lib.rs"),
]

# Category / retryability heuristics keyed by variant-name fragments.
RETRYABLE_HINTS = (
    "RateLimit", "Cooldown", "Oracle", "Timeout", "Paused", "Stale",
    "InProgress", "NotExpired", "NotStarted", "CircuitBreaker", "PartialFailure",
)
CATEGORY_HINTS = [
    (("Unauthorized", "NotAnAdmin", "NotAuthorized", "InsufficientAdmins"), "Authorization"),
    (("RateLimit", "Cooldown", "Volume", "CircuitBreaker"), "Rate Limiting"),
    (("Oracle",), "Oracle"),
    (("Paused",), "Lifecycle"),
    (("Amount", "Bps", "Interval", "Threshold", "BatchSize", "Tier"), "Validation"),
    (("NotFound", "AlreadyExists", "AlreadyProcessed", "AlreadyReleased", "AlreadyRefunded"), "State"),
    (("Expired", "Window", "Timelock", "Vesting", "Timeout"), "Timing"),
    (("Arbitration", "Dispute", "Evidence", "Clawback"), "Dispute"),
]

ENUM_RE = re.compile(r"#\[contracterror\]\s*(?:#\[derive\([^)]*\)\]\s*)?pub enum (\w+)\s*\{(.*?)\}", re.S)
VARIANT_RE = re.compile(r"^\s*(\w+)\s*=\s*(\d+)\s*,", re.M)
TS_ENTRY_RE = re.compile(r"(\w+)\s*[:=]\s*(\d+)")


def categorize(name):
    for fragments, category in CATEGORY_HINTS:
        if any(f in name for f in fragments):
            return category
    return "General"


def is_retryable(name):
    return "Yes" if any(h in name for h in RETRYABLE_HINTS) else "No"


def parse_rust(path):
    if not path.exists():
        return None, []
    text = path.read_text(encoding="utf-8")
    match = ENUM_RE.search(text)
    if not match:
        return None, []
    enum_name = match.group(1)
    variants = [(name, int(code)) for name, code in VARIANT_RE.findall(match.group(2))]
    return enum_name, variants


def parse_ts():
    if not TS_PATH.exists():
        return {}
    text = TS_PATH.read_text(encoding="utf-8")
    return {name: int(code) for name, code in TS_ENTRY_RE.findall(text)}


def build_catalog():
    catalog = []
    for display, path in CONTRACTS:
        enum_name, variants = parse_rust(path)
        catalog.append({"name": display, "enum": enum_name, "variants": variants})
    return catalog


def render(catalog):
    lines = [
        "# Error Codes Reference",
        "",
        "<!-- AUTO-GENERATED by scripts/generate-error-catalog.py. Do not edit by hand. -->",
        "",
        "This catalog is generated from the Rust `#[contracterror]` enums and cross-checked",
        "against `sdk/typescript/src/errors.ts`. Run `python3 scripts/generate-error-catalog.py`",
        "to regenerate, or `--check` in CI to verify there is no drift.",
        "",
    ]
    for contract in catalog:
        lines.append(f"## {contract['name']} Contract")
        lines.append("")
        if contract["enum"]:
            lines.append(f"### {contract['enum']}")
            lines.append("")
        lines.append("| Code | Variant | Category | Retryable | Trigger Condition | Remediation |")
        lines.append("|------|---------|----------|-----------|-------------------|-------------|")
        for name, code in contract["variants"]:
            lines.append(
                f"| {code} | {name} | {categorize(name)} | {is_retryable(name)} | "
                f"`{name}` raised by the {contract['name']} contract. | "
                f"Inspect the {contract['name']} contract state and retry with valid inputs; "
                f"never bypass authorization or security checks. |"
            )
        lines.append("")
    lines.append("## Client Integration")
    lines.append("")
    lines.append("Handle errors by matching the numeric code and surfacing the remediation above.")
    lines.append("All codes are deterministic and safe for programmatic handling.")
    lines.append("")
    return "\n".join(lines)


def check(catalog, ts_map):
    errors = []
    for contract in catalog:
        seen = {}
        for name, code in contract["variants"]:
            if code in seen:
                errors.append(f"{contract['name']}: duplicate code {code} ({seen[code]} / {name})")
            seen[code] = name
            if name in ts_map and ts_map[name] != code:
                errors.append(
                    f"{contract['name']}: TS mismatch for {name} (rust={code}, ts={ts_map[name]})"
                )
    rust_names = {name for c in catalog for name, _ in c["variants"]}
    for name in ts_map:
        if name not in rust_names:
            errors.append(f"TS SDK documents unknown error variant: {name}")
    if DOCS_PATH.exists():
        docs = DOCS_PATH.read_text(encoding="utf-8")
        for contract in catalog:
            for name, code in contract["variants"]:
                if f"| {code} | {name} |" not in docs:
                    errors.append(f"docs/ERROR_CODES.md missing {contract['name']}.{name} ({code})")
    return errors


def main():
    parser = argparse.ArgumentParser(description="Generate/verify the error catalog.")
    parser.add_argument("--check", action="store_true", help="Exit non-zero on drift.")
    args = parser.parse_args()

    catalog = build_catalog()
    ts_map = parse_ts()

    if args.check:
        errors = check(catalog, ts_map)
        if errors:
            for err in errors:
                print(f"error: {err}", file=sys.stderr)
            return 1
        print("Error catalog is in sync.")
        return 0

    DOCS_PATH.parent.mkdir(parents=True, exist_ok=True)
    DOCS_PATH.write_text(render(catalog), encoding="utf-8")
    print(f"Wrote {DOCS_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
